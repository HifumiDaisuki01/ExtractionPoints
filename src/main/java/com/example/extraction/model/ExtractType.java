package com.example.extraction.model;

/**
 * 撤离点类型。
 */
public enum ExtractType {

    /**
     * 常规撤离：玩家进入区域后独立计时，每个玩家各自计时，离开后重置。
     */
    NORMAL,

    /**
     * 拉闸撤离：玩家拉闸后触发一个全局倒计时，倒计时结束时仍在区域内的玩家撤离。
     * 倒计时期间玩家在区域内可见 BossBar 倒计时，离开区域 BossBar 消失，但倒计时继续。
     * 倒计时结束未撤离的玩家需要重新拉闸。
     */
    SWITCH,

    /**
     * 物品撤离：玩家进入区域后独立计时，且必须持有指定物品（可选消耗）。
     * 玩家各自计时，离开后重置。
     */
    ITEM
}
